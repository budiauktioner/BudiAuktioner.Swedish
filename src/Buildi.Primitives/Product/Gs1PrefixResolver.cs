    internal static (string Name, string? CountryCode)? Resolve(string prefix)
    {
        if (prefix.Length < 1) return null;

        if (!int.TryParse(prefix.Length <= 3 ? prefix : prefix[..3], out var num))
            return null;

        foreach (var (from, to, name, code) in Ranges)
        {
            if (num >= from && num <= to)
                return (name, code);
        }

        return null;
    }

namespace Buildi.Primitives.Geography;

/// <summary>
/// Extension methods for geography-related types.
/// </summary>
/// <remarks>
/// Municipality adjacency data is derived from SCB's digital boundary files
/// (<see href="https://www.scb.se/en/services/ordering-data-and-statistics/inquiry-for-statistical-tables/geographical-divisions-and-digital-boundaries/">Digitala gränser</see>)
/// using polygon intersection, as compiled by
/// <see href="https://github.com/kpalmvik/grannkommuner">kpalmvik/grannkommuner</see>.
/// Island municipalities with no shared land borders (e.g. Ekerö, Lidingö, Gotland, Öckerö, Tjörn) return an empty list.
/// County adjacency is derived from the municipality adjacency: two counties are adjacent when at least one municipality
/// in each county shares a border.
/// </remarks>
public static class GeographyExtensions
{
    /// <summary>
    /// Returns all municipalities belonging to this county, ordered by municipality code.
    /// </summary>
    public static IReadOnlyList<SwedishMunicipality> GetMunicipalities(this SwedishCounty county)
        => SwedishMunicipality.All.Where(m => m.CountyCode == county.Code).ToList();

    /// <summary>
    /// Returns all municipalities that share a land border with this municipality.
    /// Island municipalities with no land borders return an empty list.
    /// </summary>
    public static IReadOnlyList<SwedishMunicipality> GetAdjacentMunicipalities(this SwedishMunicipality municipality)
    {
        if (!MunicipalityAdjacency.TryGetValue(municipality.Code, out var codes))
            return [];

        var result = new List<SwedishMunicipality>(codes.Length);
        foreach (var code in codes)
            if (SwedishMunicipality.TryParse(code, out var neighbor) && neighbor is not null)
                result.Add(neighbor);
        return result;
    }

    /// <summary>
    /// Returns all counties that share a land border with this county.
    /// Gotland returns an empty list as it has no land borders.
    /// </summary>
    public static IReadOnlyList<SwedishCounty> GetAdjacentCounties(this SwedishCounty county)
    {
        if (!CountyAdjacency.TryGetValue(county.Code, out var codes))
            return [];

        var result = new List<SwedishCounty>(codes.Length);
        foreach (var code in codes)
            if (SwedishCounty.TryParse(code, out var neighbor) && neighbor is not null)
                result.Add(neighbor);
        return result;
    }


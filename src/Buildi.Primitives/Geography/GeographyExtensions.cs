    /// <summary>
    /// Returns all countries that share a land border with this country.
    /// Island nations and territories with no land borders (e.g. Iceland, Japan, Australia) return an empty list.
    /// </summary>
    /// <remarks>
    /// Border data sourced from <see href="https://www.wikidata.org/wiki/Property:P47">Wikidata P47</see>
    /// and maintained as package-curated adjacency metadata.
    /// </remarks>
    public static IReadOnlyList<Country> GetBorderingCountries(this Country country)
    {
        if (!CountryBorders.TryGetValue(country.Alpha2Code, out var codes))
            return [];

        var result = new List<Country>(codes.Length);
        foreach (var code in codes)
            if (Country.TryParse(code, out var neighbor) && neighbor is not null)
                result.Add(neighbor);
        return result;
    }

    /// <summary>
    /// Returns all countries on this continent, ordered by English name.
    /// </summary>
    public static IReadOnlyList<Country> GetCountries(this Continent continent) =>
        Country.All.Where(c => c.Continent == continent).OrderBy(c => c.EnglishName).ToList();

